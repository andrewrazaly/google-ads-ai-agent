export function formatSearchTermsForPrompt(data: typeof syntheticSearchTermsData) {
  let formatted = "Search Term | Impressions | Clicks | Cost | Conversions | Conv. Value | CTR | CPA | Conv. Rate\n";
  formatted += "---|---|---|---|---|---|---|---|---\n";

  data.forEach(row => {
    formatted += `${row.searchTerm} | ${row.impressions} | ${row.clicks} | $${row.cost.toFixed(2)} | ${row.conversions} | $${row.conversionValue.toFixed(2)} | ${row.ctr.toFixed(1)}% | ${row.cpa > 0 ? '$' + row.cpa.toFixed(2) : 'N/A'} | ${row.conversionRate.toFixed(1)}%\n`;
  });

  return formatted;
}

